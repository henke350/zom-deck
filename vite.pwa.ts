import { readdirSync } from 'node:fs'
import type { Plugin } from 'vite'

/**
 * Makes the built game installable and playable offline (a PWA, "Progressive Web App").
 * At build time it writes `sw.js`, a service worker that stores every file of this build
 * on the device. A new build gets a new cache name, so the next start picks up the update.
 */
export function offlineApp(): Plugin {
  return {
    name: 'offline-app',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = [
        './',
        ...Object.keys(bundle).map((file) => `./${file}`),
        ...readdirSync('public').map((file) => `./${file}`),
      ].sort()
      const version = hash(files.join('\n'))
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: serviceWorker(`omb-${version}`, files),
      })
    },
  }
}

function hash(text: string): string {
  let h = 2166136261
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 16777619)
  return (h >>> 0).toString(36)
}

function serviceWorker(cache: string, files: readonly string[]): string {
  return `// Generated by vite.pwa.ts – do not edit.
const CACHE = ${JSON.stringify(cache)}
const FILES = ${JSON.stringify(files)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

// Pages: the network first (to get updates), the stored copy when offline.
// Everything else: the stored copy first; its file name changes when it changes.
self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('./', { ignoreSearch: true, ignoreVary: true })))
    return
  }
  event.respondWith(caches.match(request, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(request)))
})
`
}
